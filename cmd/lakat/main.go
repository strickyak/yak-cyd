func usage() {
	fmt.Fprintf(os.Stderr, `Usage: lakat <command> [options]

Commands:
  compile   Compile LGolf (.lgolf) source files into an LCode .lapp binary (or .lasm with -S)
  asm       Assemble an LCode (.lasm) assembly file into an LCode .lapp binary
  dis       Disassemble an LCode .lapp or LCOD binary into .lasm assembly
  run       Run an LCode .lapp binary in the headless 320x240 RGB565 emulator
  upload    Upload a .lapp binary to the Lakatos Superhighway HTTP server
  push      Upload a file from the Linux PC to a destination in the Lakatos VFS (/flash, /sd, /net)
  tether    Connect to CYD over USB serial (--wire=/dev/ttyUSB0), stream logs, and send stdin commands
  imagine   Recursively resize images in SRC_DIR into 320x240 PNG or JPEG files in DEST_DIR
`)
	os.Exit(2)
}

type tapFlag []string

func (t *tapFlag) String() string { return strings.Join(*t, ",") }
func (t *tapFlag) Set(v string) error {
	*t = append(*t, v)
	return nil
}

func parseTapSpec(s string) (lakat.TouchEvent, error) {
	if idx := strings.IndexByte(s, '@'); idx >= 0 {
		s = s[:idx]
	}
	parts := strings.Split(s, ",")
	if len(parts) != 2 {
		return lakat.TouchEvent{}, fmt.Errorf("invalid --tap %q (expected x,y)", s)
	}
	x, err := strconv.Atoi(strings.TrimSpace(parts[0]))
	if err != nil {
		return lakat.TouchEvent{}, err
	}
	y, err := strconv.Atoi(strings.TrimSpace(parts[1]))
	if err != nil {
		return lakat.TouchEvent{}, err
	}
	return lakat.TouchEvent{Touched: true, X: x, Y: y}, nil
}

func writeSeedHeader(headerPath, varName, title string, lappBytes []byte) error {
	var sb strings.Builder
	sb.WriteString("// Auto-generated by lakat compile -seed-header — DO NOT EDIT\n")
	sb.WriteString("#pragma once\n#include <stdint.h>\n#include <pgmspace.h>\n\n")
	fmt.Fprintf(&sb, "// Title: %s (%d bytes)\n", title, len(lappBytes))
	fmt.Fprintf(&sb, "static const uint8_t %s[%d] PROGMEM = {\n", varName, len(lappBytes))
	for i, b := range lappBytes {
		if i%16 == 0 {
			sb.WriteString("  ")
		}
		fmt.Fprintf(&sb, "0x%02x,", b)
		if i%16 == 15 || i == len(lappBytes)-1 {
			sb.WriteByte('\n')
		} else {
			sb.WriteByte(' ')
		}
	}
	sb.WriteString("};\n")
	if err := os.MkdirAll(filepath.Dir(headerPath), 0755); err != nil {
		return err
	}
	return os.WriteFile(headerPath, []byte(sb.String()), 0644)
}

func cmdCompile(args []string) {
	fs := flag.NewFlagSet("compile", flag.ExitOnError)
	outPath := fs.String("o", "", "Output .lapp (or .lasm with -S) file path")
	title := fs.String("title", "", "Application title embedded in Lakatos .lapp header")
	emitAsm := fs.Bool("S", false, "Emit LCode assembly (.lasm) instead of binary .lapp")
	seedHeader := fs.String("seed-header", "", "Optional C header output path for embedding in firmware")
	seedVar := fs.String("seed-var", "kSeedLifeLapp", "C array identifier for -seed-header")
	fs.Parse(args)

	files := fs.Args()
	if len(files) == 0 {
		fmt.Fprintln(os.Stderr, "lakat compile: expected at least one .lgolf source file")
		os.Exit(1)
	}

	var sources []string
	for _, f := range files {
		b, err := os.ReadFile(f)
		if err != nil {
			fmt.Fprintf(os.Stderr, "lakat compile: %v\n", err)
			os.Exit(1)
		}
		sources = append(sources, string(b))
	}

	appTitle := *title
	if appTitle == "" {
		base := filepath.Base(files[0])
		appTitle = strings.TrimSuffix(base, filepath.Ext(base))
	}

	if *emitAsm {
		asmText, err := lakat.CompileToAsm(sources...)
		if err != nil {
			fmt.Fprintf(os.Stderr, "lakat compile error: %v\n", err)
			os.Exit(1)
		}
		if *outPath == "" || *outPath == "-" {
			fmt.Print(asmText)
			return
		}
		if err := os.MkdirAll(filepath.Dir(*outPath), 0755); err != nil {
			fmt.Fprintf(os.Stderr, "lakat compile: %v\n", err)
			os.Exit(1)
		}
		if err := os.WriteFile(*outPath, []byte(asmText), 0644); err != nil {
			fmt.Fprintf(os.Stderr, "lakat compile: %v\n", err)
			os.Exit(1)
		}
		return
	}

	lappBytes, _, err := lakat.CompileToLapp(appTitle, sources...)
	if err != nil {
		fmt.Fprintf(os.Stderr, "lakat compile error: %v\n", err)
		os.Exit(1)
	}

	if *outPath == "" {
		base := filepath.Base(files[0])
		*outPath = strings.TrimSuffix(base, filepath.Ext(base)) + ".lapp"
	}

	if err := os.MkdirAll(filepath.Dir(*outPath), 0755); err != nil {
		fmt.Fprintf(os.Stderr, "lakat compile: %v\n", err)
		os.Exit(1)
	}
	if err := os.WriteFile(*outPath, lappBytes, 0644); err != nil {
		fmt.Fprintf(os.Stderr, "lakat compile: %v\n", err)
		os.Exit(1)
	}

	if *seedHeader != "" {
		if err := writeSeedHeader(*seedHeader, *seedVar, appTitle, lappBytes); err != nil {
			fmt.Fprintf(os.Stderr, "lakat compile -seed-header: %v\n", err)
			os.Exit(1)
		}
	}

	fmt.Printf("Compiled %s -> %s (%d bytes total, title=%q)\n",
		strings.Join(files, " "), *outPath, len(lappBytes), appTitle)
}

func cmdAsm(args []string) {
	fs := flag.NewFlagSet("asm", flag.ExitOnError)
	outPath := fs.String("o", "", "Output .lapp file path")
	title := fs.String("title", "", "Application title embedded in Lakatos .lapp header")
	fs.Parse(args)

	if fs.NArg() != 1 {
		fmt.Fprintln(os.Stderr, "lakat asm: expected exactly one .lasm file")
		os.Exit(1)
	}
	inFile := fs.Arg(0)
	b, err := os.ReadFile(inFile)
	if err != nil {
		fmt.Fprintf(os.Stderr, "lakat asm: %v\n", err)
		os.Exit(1)
	}
	appTitle := *title
	if appTitle == "" {
		base := filepath.Base(inFile)
		appTitle = strings.TrimSuffix(base, filepath.Ext(base))
	}
	lappBytes, err := lakat.AssembleLapp(string(b), appTitle)
	if err != nil {
		fmt.Fprintf(os.Stderr, "lakat asm error: %v\n", err)
		os.Exit(1)
	}
	if *outPath == "" {
		base := filepath.Base(inFile)
		*outPath = strings.TrimSuffix(base, filepath.Ext(base)) + ".lapp"
	}
	if err := os.MkdirAll(filepath.Dir(*outPath), 0755); err != nil {
		fmt.Fprintf(os.Stderr, "lakat asm: %v\n", err)
		os.Exit(1)
	}
	if err := os.WriteFile(*outPath, lappBytes, 0644); err != nil {
		fmt.Fprintf(os.Stderr, "lakat asm: %v\n", err)
		os.Exit(1)
	}
	fmt.Printf("Assembled %s -> %s (%d bytes)\n", inFile, *outPath, len(lappBytes))
}

func cmdDis(args []string) {
	fs := flag.NewFlagSet("dis", flag.ExitOnError)
	fs.Parse(args)
	if fs.NArg() != 1 {
		fmt.Fprintln(os.Stderr, "lakat dis: expected one .lapp file")
		os.Exit(1)
	}
	b, err := os.ReadFile(fs.Arg(0))
	if err != nil {
		fmt.Fprintf(os.Stderr, "lakat dis: %v\n", err)
		os.Exit(1)
	}
	txt, err := lakat.Disassemble(b)
	if err != nil {
		fmt.Fprintf(os.Stderr, "lakat dis: %v\n", err)
		os.Exit(1)
	}
	fmt.Print(txt)
}

func cmdRun(args []string) {
	fs := flag.NewFlagSet("run", flag.ExitOnError)
	steps := fs.Int("steps", 500000, "Maximum VM instructions to execute")
	ascii := fs.Bool("ascii", false, "Print an ASCII art preview of the 320x240 TFT screen")
	dumpPPM := fs.String("dump-ppm", "", "Write 320x240 RGB565 framebuffer to a .ppm image file")
	vfsRoot := fs.String("vfs", "build", "Host root directory mapped to VFS /flash, /sd, /net")
	var taps tapFlag
	fs.Var(&taps, "tap", "Inject a touchscreen tap x,y (may be repeated)")
	fs.Parse(args)

	if fs.NArg() != 1 {
		fmt.Fprintln(os.Stderr, "lakat run: expected one .lapp file")
		os.Exit(1)
	}
	b, err := os.ReadFile(fs.Arg(0))
	if err != nil {
		fmt.Fprintf(os.Stderr, "lakat run: %v\n", err)
		os.Exit(1)
	}
	vm, err := lakat.NewVM(b)
	if err != nil {
		fmt.Fprintf(os.Stderr, "lakat run: %v\n", err)
		os.Exit(1)
	}
	vm.MaxInstructions = *steps
	vm.VfsRoot = *vfsRoot
	if *vfsRoot != "" {
		for _, sub := range []string{"flash", "sd", "net"} {
			_ = os.MkdirAll(filepath.Join(*vfsRoot, sub), 0o755)
		}
	}
	var stdoutBuf bytes.Buffer
	vm.Stdout = &stdoutBuf

	for _, ts := range taps {
		ev, err := parseTapSpec(ts)
		if err != nil {
			fmt.Fprintf(os.Stderr, "lakat run: %v\n", err)
			os.Exit(1)
		}
		vm.TouchQueue = append(vm.TouchQueue, ev)
	}

	exitCode, err := vm.Run()
	if stdoutBuf.Len() > 0 {
		fmt.Print(stdoutBuf.String())
	}
	if err != nil && !strings.Contains(err.Error(), "instruction limit") {
		fmt.Fprintf(os.Stderr, "VM runtime error at PC=%d (step %d): %v\n", vm.PC, vm.InstructionCount, err)
		os.Exit(1)
	}
	if *dumpPPM != "" {
		if err := vm.SavePPM(*dumpPPM); err != nil {
			fmt.Fprintf(os.Stderr, "lakat run -dump-ppm: %v\n", err)
			os.Exit(1)
		}
		fmt.Printf("Saved 320x240 framebuffer to %s\n", *dumpPPM)
	}
	if *ascii {
		fmt.Println("=== 320x240 TFT Screen Preview (80x30 ASCII) ===")
		fmt.Print(vm.RenderASCII())
	}
	fmt.Printf("VM finished: running=%v exit=%d steps=%d\n",
		vm.Running, exitCode, vm.InstructionCount)
}

func cmdUpload(args []string) {
	fs := flag.NewFlagSet("upload", flag.ExitOnError)
	baseURL := fs.String("url", "http://pizga.net:1908/", "Superhighway base URL")
	userPass := fs.String("u", "", "Optional Basic Auth user:password (or set CYD_SH_USER / CYD_SH_PASS)")
	fs.Parse(args)

	if fs.NArg() < 1 || fs.NArg() > 2 {
		fmt.Fprintln(os.Stderr, "Usage: lakat upload [-url http://pizga.net:1908/] [-u user:pass] <file.lapp> [remote_name.lapp]")
		os.Exit(1)
	}
	localPath := fs.Arg(0)
	remoteName := filepath.Base(localPath)
	if fs.NArg() == 2 {
		remoteName = strings.TrimLeft(fs.Arg(1), "/")
	}

	data, err := os.ReadFile(localPath)
	if err != nil {
		fmt.Fprintf(os.Stderr, "lakat upload: %v\n", err)
		os.Exit(1)
	}

	u := strings.TrimRight(*baseURL, "/") + "/" + remoteName
	client := &http.Client{Timeout: 20 * time.Second}

	req, err := http.NewRequest(http.MethodPut, u, bytes.NewReader(data))
	if err != nil {
		fmt.Fprintf(os.Stderr, "lakat upload: %v\n", err)
		os.Exit(1)
	}
	req.Header.Set("Content-Type", "application/octet-stream")

	auth := *userPass
	if auth == "" {
		envUser := os.Getenv("CYD_SH_USER")
		envPass := os.Getenv("CYD_SH_PASS")
		if envPass != "" {
			if envUser == "" {
				envUser = "lakatos"
			}
			auth = envUser + ":" + envPass
		}
	}
	if auth != "" {
		parts := strings.SplitN(auth, ":", 2)
		if len(parts) == 2 {
			req.SetBasicAuth(parts[0], parts[1])
		} else {
			req.SetBasicAuth("lakatos", parts[0])
		}
	}

	resp, err := client.Do(req)
	if err != nil {
		fmt.Fprintf(os.Stderr, "lakat upload failed: %v\n", err)
		os.Exit(1)
	}
	defer resp.Body.Close()
	body, _ := io.ReadAll(resp.Body)
	if resp.StatusCode < 200 || resp.StatusCode >= 300 {
		fmt.Fprintf(os.Stderr, "lakat upload HTTP %d: %s\n", resp.StatusCode, strings.TrimSpace(string(body)))
		os.Exit(1)
	}
	fmt.Printf("Uploaded %s (%d bytes) -> %s [HTTP %d]\n", localPath, len(data), u, resp.StatusCode)
}

func main() {
	if len(os.Args) < 2 {
		usage()
	}
	switch os.Args[1] {
	case "compile":
		cmdCompile(os.Args[2:])
	case "asm":
		cmdAsm(os.Args[2:])
	case "dis":
		cmdDis(os.Args[2:])
	case "run":
		cmdRun(os.Args[2:])
	case "upload":
		cmdUpload(os.Args[2:])
	case "push":
		cmdPush(os.Args[2:])
	case "tether":
		cmdTether(os.Args[2:])
	case "imagine":
		cmdImagine(os.Args[2:])
	default:
		usage()
	}
}
